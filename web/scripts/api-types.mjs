// Generates web/src/api/gen/<service>.ts from ../openapi/<service>.json (written by `make openapi`).
// - Identity headers (x-user-id, x-role, ...) and Authorization are set by Traefik / the client, so they are
//   removed from the operations' parameters.
// - Idempotency-Key is removed too; the operations that take it are listed in gen/idempotent.ts and the
//   client adds the header (see src/api/client.ts).
import fs from 'node:fs';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const root = path.resolve(import.meta.dirname, '..');
const src = path.resolve(root, '../openapi');
const out = path.resolve(root, 'src/api/gen');
const DROP = new Set(['x-user-id', 'x-role', 'x-branch-ids', 'x-is-pharmacist', 'x-permissions', 'authorization', 'idempotency-key']);
// The UI talks to these; ai is S10.
const SERVICES = ['auth', 'branch', 'catalog', 'inventory', 'stockcount', 'prescription', 'controlled', 'sales',
  'customers', 'purchasing', 'reports', 'notifications', 'documents'];

fs.mkdirSync(out, { recursive: true });
const idempotent = [];
for (const name of SERVICES) {
  const file = path.join(src, `${name}.json`);
  if (!fs.existsSync(file)) throw new Error(`${file} is missing: run \`make openapi\` first`);
  const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const [p, ops] of Object.entries(doc.paths)) {
    for (const [method, op] of Object.entries(ops)) {
      if (!op || typeof op !== 'object' || !Array.isArray(op.parameters)) continue;
      if (op.parameters.some((x) => x.in === 'header' && x.name.toLowerCase() === 'idempotency-key')) {
        idempotent.push(`${method.toUpperCase()} ${p}`);
      }
      op.parameters = op.parameters.filter((x) => !(x.in === 'header' && DROP.has(x.name.toLowerCase())));
      if (op.parameters.length === 0) delete op.parameters;
    }
  }
  const ast = await openapiTS(doc, { alphabetize: true, defaultNonNullable: false });
  const header = `// Generated by scripts/api-types.mjs from openapi/${name}.json. Do not edit.\n/* eslint-disable */\n`;
  fs.writeFileSync(path.join(out, `${name}.ts`), header + astToString(ast));
}
idempotent.sort();
fs.writeFileSync(
  path.join(out, 'idempotent.ts'),
  `// Generated by scripts/api-types.mjs. Operations that take an Idempotency-Key header.\n` +
    `export const IDEMPOTENT: ReadonlySet<string> = new Set(${JSON.stringify(idempotent, null, 2)});\n`,
);
console.log(`api-types: ${SERVICES.length} services, ${idempotent.length} idempotent operations`);
